#!/usr/bin/env node
/**
 * Build the self-contained Android zip for dsh-memory-sync.
 *
 * - esbuild bundles index.js + @deepseek-ai/schemastery into dist/index.js so
 *   the DSH-Android plugin settings form has a Config schema.
 * - package.json is rewritten for the bundle (no web client, root main).
 * - cordis.patch.yml is generated from a local JSON config file.
 * - The zip has package.json at its root and no UTF-8 BOM.
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import fsp from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(HERE, '..')

function arg(name, fallback = '') {
  const index = process.argv.indexOf(`--${name}`)
  return index >= 0 ? process.argv[index + 1] : fallback
}

const configFile = resolve(arg('config', join(REPO, 'tablet.config.json')))
const outFile = resolve(arg('out', join(REPO, 'dist', 'dsh-memory-sync-0.3.0-tablet.zip')))
const esbuild = arg('esbuild', process.env.ESBUILD_BIN || '')
const profileNodeModules = arg(
  'node-path',
  process.env.TABLET_NODE_PATH || 'C:/Users/QIC/.dsh/profiles/desktop/node_modules',
)

function fail(message) {
  console.error(`[build-tablet] ${message}`)
  process.exit(1)
}

function q(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}

function findEsbuild() {
  if (esbuild && fs.existsSync(esbuild)) return esbuild
  const candidates = [
    'D:/dsh-qqbot-workspace/tablet/build-qqbot/node_modules/esbuild/bin/esbuild',
    'C:/Users/QIC/.dsh/profiles/desktop/node_modules/esbuild/bin/esbuild',
    join(REPO, 'node_modules/esbuild/bin/esbuild'),
  ]
  for (const item of candidates) {
    if (fs.existsSync(item)) return item
  }
  fail('esbuild not found; pass --esbuild <path> or set ESBUILD_BIN')
}

async function main() {
  if (!fs.existsSync(configFile)) {
    fail(`config not found: ${configFile} (copy tablet.config.example.json first)`)
  }
  const config = JSON.parse(await fsp.readFile(configFile, 'utf8'))
  const stage = await fsp.mkdtemp(join(tmpdir(), 'memsync-tablet-'))
  const pkgDir = join(stage, 'package')
  await fsp.mkdir(join(pkgDir, 'dist'), { recursive: true })

  // 1. Bundle host code + schemastery.
  const esbuildBin = findEsbuild()
  const bundle = spawnSync(process.execPath, [
    esbuildBin,
    join(REPO, 'index.js'),
    '--bundle',
    '--platform=node',
    '--format=esm',
    '--target=node22',
    `--outfile=${join(pkgDir, 'dist', 'index.js')}`,
  ], {
    cwd: REPO,
    env: { ...process.env, NODE_PATH: profileNodeModules },
    encoding: 'utf8',
  })
  if (bundle.status !== 0) {
    fail(`esbuild failed:\n${bundle.stderr || bundle.stdout}`)
  }

  // 2. package.json for the bundled Android package.
  const sourcePkg = JSON.parse(await fsp.readFile(join(REPO, 'package.json'), 'utf8'))
  const pkg = {
    ...sourcePkg,
    main: './dist/index.js',
    exports: {
      '.': './dist/index.js',
      './package.json': './package.json',
    },
    files: ['dist/', 'cordis.patch.yml', 'locale/', 'icon.svg', 'README.md', 'MANUAL.md', 'LICENSE'],
  }
  delete pkg.dsh.client
  await fsp.writeFile(join(pkgDir, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`, 'utf8')

  // 3. cordis.patch.yml from the local config.
  const patch = [
    '# Tablet build generated by scripts/build-tablet.mjs. Do not edit by hand.',
    '- insert:',
    '    - id: dsh-memory-sync',
    "      name: 'dsh-memory-sync'",
    '      config:',
    `        repoPath: ${q(config.repoPath || '/data/user/0/io.github.jackwener.dsh/files/dsh-home/memories')}`,
    `        transport: ${q(config.transport || 'http')}`,
    `        peerUrl: ${q(config.peerUrl || '')}`,
    `        machine: ${q(config.machine || 'tablet')}`,
    `        memSecret: ${q(config.memSecret || '')}`,
    `        serve: ${Boolean(config.serve !== false)}`,
    `        autoApply: ${Boolean(config.autoApply !== false)}`,
    `        runOnStartup: ${Boolean(config.runOnStartup !== false)}`,
    `        intervalSendMinutes: ${Number(config.intervalSendMinutes) || 0}`,
    `        conflict: ${q(config.conflict === 'local' ? 'local' : 'peer')}`,
    `        replyOnReceive: ${Boolean(config.replyOnReceive)}`,
    `        keepSnapshots: ${Number(config.keepSnapshots) || 5}`,
    `        maxSnapshotMB: ${Number(config.maxSnapshotMB) || 100}`,
    `        enabled: ${Boolean(config.enabled !== false)}`,
    '',
  ].join('\n')
  await fsp.writeFile(join(pkgDir, 'cordis.patch.yml'), patch, 'utf8')

  // 4. Docs and assets.
  for (const name of ['README.md', 'README.en.md', 'MANUAL.md', 'LICENSE', 'icon.svg']) {
    const from = join(REPO, name)
    if (fs.existsSync(from)) await fsp.copyFile(from, join(pkgDir, name))
  }
  const localeDir = join(REPO, 'locale')
  if (fs.existsSync(localeDir)) await fsp.cp(localeDir, join(pkgDir, 'locale'), { recursive: true })

  // 5. Verify before zipping.
  const pkgBytes = await fsp.readFile(join(pkgDir, 'package.json'))
  if (pkgBytes[0] === 0xef && pkgBytes[1] === 0xbb && pkgBytes[2] === 0xbf) fail('package.json has a UTF-8 BOM')
  JSON.parse(pkgBytes.toString('utf8'))
  const dist = join(pkgDir, 'dist', 'index.js')
  const testHome = join(stage, 'home')
  const probe = spawnSync(process.execPath, [
    '--input-type=module',
    '-e',
    `import(${JSON.stringify(pathToFileURL(dist).href)}).then(m=>{console.log('CONFIG',typeof m.Config);process.exit(typeof m.Config==='undefined'?2:0)}).catch(e=>{console.error(e);process.exit(3)})`,
  ], {
    cwd: pkgDir,
    env: { ...process.env, DSH_HOME: testHome },
    encoding: 'utf8',
  })
  if (probe.status !== 0 || !/CONFIG (object|function)/.test(probe.stdout)) {
    fail(`bundled Config is missing:\n${probe.stdout}\n${probe.stderr}`)
  }

  // 6. Zip with package.json at the root.
  await fsp.mkdir(dirname(outFile), { recursive: true })
  await fsp.rm(outFile, { force: true }).catch(() => {})
  const ps = [
    'Add-Type -AssemblyName System.IO.Compression.FileSystem;',
    `[IO.Compression.ZipFile]::CreateFromDirectory(${q(pkgDir)}, ${q(outFile)}, [IO.Compression.CompressionLevel]::Optimal, $false);`,
  ].join(' ')
  const zipped = spawnSync('powershell.exe', ['-NoProfile', '-Command', ps], { encoding: 'utf8' })
  if (zipped.status !== 0) fail(`zip failed:\n${zipped.stderr || zipped.stdout}`)

  const list = spawnSync('powershell.exe', [
    '-NoProfile',
    '-Command',
    `Add-Type -AssemblyName System.IO.Compression.FileSystem; $z=[IO.Compression.ZipFile]::OpenRead(${q(outFile)}); $z.Entries | ForEach-Object { $_.FullName }; $z.Dispose()`,
  ], { encoding: 'utf8' })
  const entries = String(list.stdout || '')
    .split(/\r?\n/)
    .filter(Boolean)
    .map((name) => name.replace(/\\/g, '/'))
  for (const required of ['package.json', 'dist/index.js', 'cordis.patch.yml', 'MANUAL.md']) {
    if (!entries.includes(required)) fail(`zip is missing ${required}`)
  }
  if (entries.some((name) => name === 'client.js' || name.startsWith('node_modules/') || name.endsWith('.node'))) {
    fail('zip contains client.js/node_modules/native binaries')
  }

  const bytes = await fsp.readFile(outFile)
  const sha = createHash('sha256').update(bytes).digest('hex')
  const summary = {
    ok: true,
    zip: outFile,
    bytes: bytes.length,
    sha256: sha,
    files: entries.length,
    config: {
      peerUrl: config.peerUrl || '',
      machine: config.machine || 'tablet',
      serve: config.serve !== false,
      autoApply: config.autoApply !== false,
      conflict: config.conflict === 'local' ? 'local' : 'peer',
      intervalSendMinutes: Number(config.intervalSendMinutes) || 0,
      replyOnReceive: Boolean(config.replyOnReceive),
    },
  }
  console.log(JSON.stringify(summary, null, 2))
}

main().catch((error) => fail(String(error?.stack || error)))
